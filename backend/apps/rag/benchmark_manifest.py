@dataclass(frozen=True)
class BenchmarkCase:
    case_code: str
    category: str
    profile: str
    description: str
    query: str
    snapshot_identifier: str
    search_mode: str
    top_k: int
    evaluation_time: datetime | None
    document_type: str | None
    language: str | None
    source_kind: str | None
    rule_code: str | None
    rule_version: int | None
    expected_document_code: str
    expected_document_version: int
    expected_rule_version: int | None
    expected_heading_contains: str | None
    require_heading_match: bool
    max_accepted_rank: int
    forbidden_document_codes: tuple[str, ...] = ()
    tags: tuple[str, ...] = ()
    required_terms: tuple[str, ...] = ()
    forbidden_terms: tuple[str, ...] = ()


def _case(
    case_code,
    category,
    profile,
    description,
    query,
    snapshot_identifier,
    expected_document_code,
    *,
    search_mode="full_text",
    top_k=5,
    evaluation_time=None,
    document_type=None,
    language="tr",
    source_kind="synthetic",
    rule_code=None,
    rule_version=None,
    expected_document_version=1,
    expected_rule_version=None,
    expected_heading_contains=None,
    require_heading_match,
    max_accepted_rank=1,
    forbidden_document_codes=(),
    tags=(),
    required_terms=(),
    forbidden_terms=(),
):
    return BenchmarkCase(
        case_code=case_code,
        category=category,
        profile=profile,
        description=description,
        query=query,
        snapshot_identifier=snapshot_identifier,
        search_mode=search_mode,
        top_k=top_k,
        evaluation_time=evaluation_time,
        document_type=document_type,
        language=language,
        source_kind=source_kind,
        rule_code=rule_code,
        rule_version=rule_version,
        expected_document_code=expected_document_code,
        expected_document_version=expected_document_version,
        expected_rule_version=expected_rule_version,
        expected_heading_contains=expected_heading_contains,
        require_heading_match=require_heading_match,
        max_accepted_rank=max_accepted_rank,
        forbidden_document_codes=tuple(forbidden_document_codes),
        tags=tuple(tags),
        required_terms=tuple(required_terms),
        forbidden_terms=tuple(forbidden_terms),
    )


